"""Write gold-standard analysis scripts to disk in a uniform shape.

Every script follows this skeleton:

    \"\"\"Q<id>: <question text>
    Generated by clin-genomic-analysis-benchmark gold-standard pipeline.\"\"\"
    import json, sys
    from pathlib import Path

    def analyze(cohort_dir: Path) -> dict:
        # >>> LLM-generated body returns a dict matching the answer-type schema
        ...

    if __name__ == "__main__":
        cohort_dir = Path(sys.argv[1])
        result_path = Path(sys.argv[2])
        result = analyze(cohort_dir)
        result_path.parent.mkdir(parents=True, exist_ok=True)
        result_path.write_text(json.dumps(result, indent=2, default=str))
"""

from __future__ import annotations

import textwrap
from pathlib import Path

from ..config import gold_standard_dir


def script_path(cohort: str, question_id: str) -> Path:
    return gold_standard_dir() / cohort / f"{question_id}.py"


def result_path(cohort: str, question_id: str) -> Path:
    return gold_standard_dir() / cohort / f"{question_id}.result.json"


def log_path(cohort: str, question_id: str) -> Path:
    return gold_standard_dir() / cohort / f"{question_id}.log"


_HEADER = textwrap.dedent('''\
    """{qid}: {qtext}

    Auto-generated by clin-genomic-analysis-benchmark gold-standard pipeline.
    Answer type: {answer_type}
    Cohort: {cohort}
    """
    from __future__ import annotations
    import json
    import sys
    from pathlib import Path

    import numpy as np
    import pandas as pd
''')


_FOOTER = textwrap.dedent('''

    if __name__ == "__main__":
        cohort_dir = Path(sys.argv[1])
        result_path = Path(sys.argv[2])
        result = analyze(cohort_dir)
        if not isinstance(result, dict):
            raise TypeError(f"analyze() must return a dict, got {type(result).__name__}")
        result_path.parent.mkdir(parents=True, exist_ok=True)
        result_path.write_text(json.dumps(result, indent=2, default=str))
''')


def assemble(*, cohort: str, qid: str, qtext: str, answer_type: str, body: str) -> str:
    """Assemble a complete script from the LLM-generated `body`.

    The body must define a top-level function `def analyze(cohort_dir: Path) -> dict`.
    """
    body = body.strip("\n")
    return _HEADER.format(qid=qid, qtext=qtext.replace('"', "'"),
                          answer_type=answer_type, cohort=cohort) + "\n\n" + body + _FOOTER


def write(*, cohort: str, qid: str, qtext: str, answer_type: str, body: str) -> Path:
    p = script_path(cohort, qid)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(assemble(cohort=cohort, qid=qid, qtext=qtext, answer_type=answer_type, body=body))
    return p
